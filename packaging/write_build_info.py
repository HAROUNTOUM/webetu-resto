"""Write src/webetu_resto/_build.py during a release build.

It records which GitHub repository and version the program was built from, so
the interface can tell the student when a newer version is available.
"""

from __future__ import annotations

import os
from pathlib import Path


def main() -> None:
    repo = os.environ.get("GITHUB_REPOSITORY", "")
    ref_type = os.environ.get("GITHUB_REF_TYPE", "")
    ref_name = os.environ.get("GITHUB_REF_NAME", "")
    version = ref_name.lstrip("vV") if ref_type == "tag" else "0.0.0-dev"
    target = Path(__file__).resolve().parent.parent / "src" / "webetu_resto" / "_build.py"
    content = (
        '"""Generated by packaging/write_build_info.py during a release build."""\n\n'
        f"REPO = {repo!r}\n"
        f"VERSION = {version!r}\n"
    )
    target.write_text(content, encoding="utf-8")
    print(f"wrote {target}: REPO={repo!r} VERSION={version!r}")


if __name__ == "__main__":
    main()
